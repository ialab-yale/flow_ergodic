    @classmethod
    def _cow_marker(cls):
        m = parse_path(cls.cow_svg)
        m.vertices -= m.vertices.mean(axis=0)
        m.vertices  = -m.vertices
        return m

    ## =========================================================================

    def __init__(self, input_args):
        self.input_args = input_args

        self.N = input_args.get('N', 20)
        self.T = input_args.get('T', 300)
        self.grid_res = input_args.get('grid_res', 50)

        # Dynamics
        self.dt = 0.02
        self.k_v = 1.5
        self.k_d = 7.0
        self.k_r = 0.005
        self.k_r_damp = 0.8
        self.cow_rep_r = 0.2

        # Walls
        self.k_wr = 0.05
        self.crit_dist = 0.15
        self.wall_pad = 0.2
        self.max_wall_f = 5.0

        # Sinks
        self.sink_stab_r = 0.1
        self.k_sink_rep = 0.5
        self.sink_rep_r = 0.1

        # Aggression
        self.n_aggressive = 2
        self.anger_r = 0.1

        # Geometry
        self.extent = [0.5, 4.5, 0.5, 4.5]
        self.sinks = np.array([[1.8, 1.8], [3.7, 1.7], [1.8, 3.6]])

        self.P = np.zeros((self.N, 2))
        self.V = np.zeros((self.N, 2))
        self.t = 0.0

        self.centers = []
        self.anger = []

        self.aggressive = np.zeros(self.N, dtype=bool)

        if self.N > self.n_aggressive:
            idx = np.random.choice(self.N, self.n_aggressive, replace=False)
            self.aggressive[idx] = True
        elif self.N > 0:
            self.aggressive[:] = True

        self.angry = np.zeros(self.N, dtype=bool)

        self._init_pos()

    ## =========================================================================

    def _init_pos(self):
        x_min, x_max, y_min, y_max = self.extent

        self.P[:, 0] = np.random.uniform(x_min + self.wall_pad, x_max - self.wall_pad, self.N)
        self.P[:, 1] = np.random.uniform(y_min + self.wall_pad, y_max - self.wall_pad, self.N)

        self.V = np.zeros((self.N, 2))

    def get_sink_flow(self, p):
        dists = np.linalg.norm(self.sinks - p, axis=1)
        idx = np.argmin(dists)

        d = dists[idx]
        r = self.sinks[idx] - p
        mag = self.k_v * d / (d**2 + self.sink_stab_r**2)

        return mag * r / (d + 1e-6)

    def get_sink_rep(self, p):
        dists = np.linalg.norm(self.sinks - p, axis=1)
        idx = np.argmin(dists)

        d = dists[idx]
        F = np.zeros(2)

        if 1e-6 < d < self.sink_rep_r:
            u = (self.sinks[idx] - p) / d
            F = -(self.k_sink_rep / d**2) * u

        return F

    def get_wall_rep(self, p):
        x_min, x_max, y_min, y_max = self.extent
        F = np.zeros(2)

        for d, sign, axis in [
            (p[0] - x_min, +1, 0),
            (x_max - p[0], -1, 0),
            (p[1] - y_min, +1, 1),
            (y_max - p[1], -1, 1)]:

            if 1e-6 < d < self.crit_dist:
                F[axis] += sign * min(self.k_wr / d, self.max_wall_f)

        return F

    def update_anger(self):
        new_angry = np.zeros(self.N, dtype=bool)

        for i in np.where(self.aggressive)[0]:
            dists = np.linalg.norm(self.P - self.P[i], axis=1)
            dists[i] = self.anger_r + 1

            if np.any(dists < self.anger_r):
                new_angry[i] = True

        self.angry = new_angry

    def calc_accel(self, i):
        p_i, v_i = self.P[i], self.V[i]
        F = self.get_sink_flow(p_i) + self.get_sink_rep(p_i) + self.get_wall_rep(p_i)

        for j in range(self.N):
            if i == j:
                continue
            r_ij = p_i - self.P[j]
            dist = np.linalg.norm(r_ij)

            if 1e-6 < dist < self.cow_rep_r:
                r_hat = r_ij / dist
                v_rel = v_i - self.V[j]

                F += (self.k_r / dist**2) * r_hat
                F -= self.k_r_damp * v_rel * (self.cow_rep_r - dist)

        F -= self.k_d * v_i
        return F

    def step(self):
        self.update_anger()

        dv_dt = np.array([self.calc_accel(i) for i in range(self.N)])

        self.V += dv_dt * self.dt
        self.P += self.V  * self.dt
        self.t += self.dt

        self.P[:, 0] = np.clip(self.P[:, 0], self.extent[0] + 1e-4, self.extent[1] - 1e-4)
        self.P[:, 1] = np.clip(self.P[:, 1], self.extent[2] + 1e-4, self.extent[3] - 1e-4)

        self.centers.append(self.P.copy())
        self.anger.append(self.angry.copy())

    ## =========================================================================

    def make_flow(self):
        print(f"Running simulation (T = {self.T})...")
        for i in range(self.T):
            if i % 50 == 0:
                sys.stdout.write(f"\rStep {i}/{self.T}")
                sys.stdout.flush()
            self.step()
        print(f"\rSim complete.")

    def animate(self, save=True, filename='cattle_flow.mp4'):
        x_min, x_max, y_min, y_max = self.extent

        fig, ax = plt.subplots(figsize=(8, 8), facecolor='white')
        ax.set_facecolor('white')
        ax.set_xlim(x_min - 0.25, x_max + 0.25)
        ax.set_ylim(y_min - 0.25, y_max + 0.25)
        ax.set_aspect('equal')
        ax.axis('off')

        x_g = np.linspace(x_min, x_max, 30)
        y_g = np.linspace(y_min, y_max, 30)
        Xm, Ym = np.meshgrid(x_g, y_g)
        Um, Vm = np.zeros_like(Xm), np.zeros_like(Ym)
        for i in range(Xm.shape[0]):
            for j in range(Xm.shape[1]):
                vel          = self.get_sink_flow(np.array([Xm[i, j], Ym[i, j]]))
                Um[i, j], Vm[i, j] = vel
        Mag = np.sqrt(Um**2 + Vm**2) + 1e-6
        ax.streamplot(Xm, Ym, Um / Mag, Vm / Mag,
                      color='#bbbbbb', density=1.0, linewidth=1.0, arrowsize=1.2, zorder=1)

        ax.plot([x_min, x_max, x_max, x_min, x_min],
                [y_min, y_min, y_max, y_max, y_min],
                color='#333333', linewidth=2.5, solid_capstyle='round', zorder=2)

        ax.plot(self.sinks[:, 0], self.sinks[:, 1],
                'o', color='chocolate', markersize=14, zorder=4)

        P0 = self.centers[0] if self.centers else self.P
        A0 = self.anger[0]   if self.anger   else self.angry
        scatter = ax.scatter(P0[:, 0], P0[:, 1],
                             c=np.where(A0, '#ff1a1a', '#1a1a1a'),
                             marker=self._cow_marker(),
                             s=300, edgecolors='none', zorder=10)

        time_text = ax.text(0.02, 0.97, 't = 0.0 s',
                            transform=ax.transAxes,
                            fontsize=9, va='top', ha='left',
                            color='#666666', fontfamily='monospace')

        ax.invert_xaxis()
        ax.invert_yaxis()

        T_frames = len(self.centers)

        def update(k):
            scatter.set_offsets(self.centers[k])
            scatter.set_facecolors(np.where(self.anger[k], '#ff1a1a', '#1a1a1a'))
            time_text.set_text(f't = {k * self.dt:.1f} s')
            sys.stdout.write(f"\rFrame {k + 1}/{T_frames}")
            sys.stdout.flush()
            return scatter, time_text

        ani = FuncAnimation(fig, update, frames=T_frames,
                            blit=True, interval=self.dt * 1000, repeat=False)

        if save:
            print(f"\nSaving animation...")
            ani.save(filename, writer=animation.FFMpegWriter(fps=30),
                     savefig_kwargs={'facecolor': 'white'})
            print(f"\nSaved to {filename}")
        else:
            plt.show()

        plt.close(fig)

    def save_flow(self, filename='cattle_data.npz'):        
        x_min, x_max, y_min, y_max = self.extent

        x = np.linspace(x_min, x_max, self.grid_res)
        y = np.linspace(y_min, y_max, self.grid_res)

        gX, gY = np.meshgrid(x, y)
        pts = np.stack([gX.ravel(), gY.ravel()], axis=1)

        U_flat = np.zeros(len(pts))
        V_flat = np.zeros(len(pts))

        for k, pt in enumerate(pts):
            vec = self.get_sink_flow(pt) + self.get_sink_rep(pt)
            U_flat[k] = vec[0]
            V_flat[k] = vec[1]

        wall_corners = np.array([[x_min, y_min], [x_max, y_min],
                                  [x_max, y_max], [x_min, y_max], [x_min, y_min]])

        np.savez(
            filename,
            centers = np.array(self.centers),
            anger = np.array(self.anger),
            aggressive = self.aggressive,
            wall_corners = wall_corners,
            sinks = self.sinks,
            grid = np.stack([gX, gY], axis=-1),
            U = U_flat.reshape(self.grid_res, self.grid_res),
            V = V_flat.reshape(self.grid_res, self.grid_res),
            dt = self.dt,
            N = self.N,
            T = len(self.centers),
        )

        centers = np.array(self.centers)
        anger   = np.array(self.anger)
        print(f"Data saved to '{filename}'")

